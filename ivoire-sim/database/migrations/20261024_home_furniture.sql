USE ivoire_sim;

CREATE TABLE IF NOT EXISTS furniture (
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  slug       VARCHAR(60)  NOT NULL UNIQUE,
  name       VARCHAR(80)  NOT NULL,
  category   ENUM('salon','chambre','cuisine','salle_de_bain','decoration','eclairage','portes_fenetres') NOT NULL,
  price      BIGINT       NOT NULL,
  model_file VARCHAR(80)  NOT NULL,
  INDEX idx_furniture_cat (category, price)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS player_furniture (
  player_id    INT UNSIGNED NOT NULL,
  furniture_id INT UNSIGNED NOT NULL,
  quantity     INT UNSIGNED NOT NULL DEFAULT 1,
  PRIMARY KEY (player_id, furniture_id),
  FOREIGN KEY (player_id)    REFERENCES players(id)   ON DELETE CASCADE,
  FOREIGN KEY (furniture_id) REFERENCES furniture(id) ON DELETE CASCADE
) ENGINE=InnoDB;

