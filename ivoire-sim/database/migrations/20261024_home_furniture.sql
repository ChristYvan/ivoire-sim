-- ---------- Aménagement des maisons : meubles posés dans une propriété ----------
CREATE TABLE IF NOT EXISTS placed_furniture (
  id           BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  player_id    INT UNSIGNED NOT NULL,
  property_id  INT UNSIGNED NOT NULL,
  furniture_id INT UNSIGNED NOT NULL,
  x            FLOAT NOT NULL DEFAULT 0,   -- position dans la pièce (mètres, 0 = centre)
  z            FLOAT NOT NULL DEFAULT 0,
  rot          FLOAT NOT NULL DEFAULT 0,   -- rotation en radians
  INDEX idx_placed_property (property_id),
  FOREIGN KEY (player_id)    REFERENCES players(id)    ON DELETE CASCADE,
  FOREIGN KEY (property_id)  REFERENCES properties(id) ON DELETE CASCADE,
  FOREIGN KEY (furniture_id) REFERENCES furniture(id)  ON DELETE CASCADE
) ENGINE=InnoDB;
